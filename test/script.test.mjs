// generate-index script tests — the binding contract of the ONLY INDEX.md
// writer. Runs the script as a real child process against a temp DSH home
// (never the real one) and asserts on the files it leaves behind:
// generates indexes for the global store and every workspace store with
// files, ignores descriptionless files, and honestly truncates descriptions
// over 1000 chars without touching the file.

import { after, test } from 'node:test';
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { access, mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { composeIndexDocument } from '../lib/store.js';

const run = promisify(execFile);
const repo = join(dirname(fileURLToPath(import.meta.url)), '..');
const script = join(repo, 'scripts', 'generate-index.mjs');

const fx = await (async () => {
  const scratch = await mkdtemp(join(tmpdir(), 'dsh-memories-script-'));
  const home = join(scratch, 'home');
  const longTerm = join(home, 'memories', 'global-long-term');
  const wsOne = join(home, 'memories', 'workspace', 'ws-one');
  const wsEmpty = join(home, 'memories', 'workspace', 'ws-empty');
  await mkdir(longTerm, { recursive: true });
  await mkdir(wsOne, { recursive: true });
  await mkdir(wsEmpty, { recursive: true });
  await writeFile(join(longTerm, 'alpha.md'), '# Alpha\n\nDescription: First description.\n\nAlpha body.\n');
  await writeFile(join(longTerm, 'beta.md'), `# Beta\n\nDescription: ${'b'.repeat(1200)}\n\nBeta body.\n`);
  await writeFile(join(longTerm, 'gamma.md'), '# Gamma\n\nNo description here.\n');
  await writeFile(join(wsOne, 'release.md'), '# Release process\n\nDescription: Ship it.\n\nBody.\n');
  return {
    scratch,
    home,
    longTerm,
    wsOne,
    wsEmpty,
    dispose: () => rm(scratch, { recursive: true, force: true }),
  };
})();
after(() => fx.dispose());

test('generates INDEX.md for the global store and every workspace store with files', async () => {
  const { stdout } = await run(process.execPath, [script, '--home', fx.home]);
  assert.ok(stdout.includes('DSH home:'), 'the resolved home is reported');
  assert.ok(stdout.includes('memories/global-long-term: 2 entries -> INDEX.md'));
  assert.ok(stdout.includes('memories/workspace/ws-one: 1 entry -> INDEX.md'));
  assert.ok(stdout.includes('memories/workspace/ws-empty: no memory files — skipped'));
  const globalIndex = await readFile(join(fx.longTerm, 'INDEX.md'), 'utf8');
  assert.ok(globalIndex.startsWith('<!-- Generated by scripts/generate-index.mjs'));
  assert.ok(globalIndex.includes('- Alpha (alpha.md) — First description.'));
  assert.ok(globalIndex.endsWith('\n'));
  await readFile(join(fx.wsOne, 'INDEX.md'), 'utf8');
  await assert.rejects(access(join(fx.wsEmpty, 'INDEX.md')), 'an empty workspace store gets no INDEX.md');
});

test('ignores files without a Description line', async () => {
  const globalIndex = await readFile(join(fx.longTerm, 'INDEX.md'), 'utf8');
  assert.ok(!globalIndex.includes('gamma') && !globalIndex.includes('Gamma'));
  assert.ok(
    (await readFile(join(fx.longTerm, 'gamma.md'), 'utf8')).includes('No description here.'),
    'the descriptionless file itself is untouched',
  );
});

test('truncates descriptions over 1000 chars with an honest ellipsis, file untouched', async () => {
  const globalIndex = await readFile(join(fx.longTerm, 'INDEX.md'), 'utf8');
  const line = globalIndex.split(/\r?\n/).find((l) => l.startsWith('- Beta (beta.md) — '));
  assert.ok(line !== undefined, 'beta is listed');
  assert.equal(line, `- Beta (beta.md) — ${'b'.repeat(999)}…`);
  const raw = await readFile(join(fx.longTerm, 'beta.md'), 'utf8');
  assert.ok(raw.includes(`Description: ${'b'.repeat(1200)}`), 'the hand-edited file keeps its 1200-char description');
});

test('on-disk artifact is byte-identical to the plugin read-only synthesis', async () => {
  const onDisk = await readFile(join(fx.longTerm, 'INDEX.md'), 'utf8');
  assert.equal(onDisk, `${await composeIndexDocument(fx.longTerm)}\n`);
});

test('DSH_HOME env precedence works without --home', async () => {
  await rm(join(fx.longTerm, 'INDEX.md'));
  await rm(join(fx.wsOne, 'INDEX.md'));
  await run(process.execPath, [script], { env: { ...process.env, DSH_HOME: fx.home } });
  await readFile(join(fx.longTerm, 'INDEX.md'), 'utf8');
  await readFile(join(fx.wsOne, 'INDEX.md'), 'utf8');
});
