// generate-index script tests — the binding contract of the ONLY INDEX.md
// writer. The command is parameter-free and processes ONLY the memories of
// the workspace it is run in: the workspace is derived from the child
// process cwd (project-root climb → directory name → slug) exactly like a
// session's workspace, and only that store's INDEX.md is regenerated —
// never the global store, never other workspaces. Runs against a temp DSH
// home (never the real one) and asserts on the files left behind:
// generates the index, ignores descriptionless files, and honestly
// truncates descriptions over 1000 chars without touching the file.

import { after, test } from 'node:test';
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { access, mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { composeIndexDocument } from '../lib/store.js';

const run = promisify(execFile);
const repo = join(dirname(fileURLToPath(import.meta.url)), '..');
const script = join(repo, 'scripts', 'generate-index.mjs');

const fx = await (async () => {
  const scratch = await mkdtemp(join(tmpdir(), 'dsh-memories-script-'));
  const home = join(scratch, 'home');
  const globalLongTerm = join(home, 'memories', 'global-long-term');
  const wsOne = join(home, 'memories', 'workspace', 'ws-one');
  const wsOther = join(home, 'memories', 'workspace', 'ws-other');
  const nested = join(scratch, 'project', 'ws-one', 'deep', 'nested'); // cwd below the marker
  const emptyProject = join(scratch, 'project', 'ws-empty');
  await mkdir(globalLongTerm, { recursive: true });
  await mkdir(wsOne, { recursive: true });
  await mkdir(wsOther, { recursive: true });
  await mkdir(nested, { recursive: true });
  await mkdir(join(scratch, 'project', 'ws-one', '.git'), { recursive: true });
  await mkdir(emptyProject, { recursive: true });
  await mkdir(join(emptyProject, '.git'), { recursive: true });
  // The CURRENT workspace store (ws-one): described, descriptionless, over-long.
  await writeFile(join(wsOne, 'release.md'), '# Release process\n\nDescription: Ship it.\n\nBody.\n');
  await writeFile(join(wsOne, 'notes.md'), '# Notes\n\nNo description here.\n');
  await writeFile(join(wsOne, 'huge.md'), `# Huge\n\nDescription: ${'q'.repeat(1500)}\n\nBody.\n`);
  // A DIFFERENT workspace store with files — must stay untouched.
  await writeFile(join(wsOther, 'other.md'), '# Other\n\nDescription: Other store.\n\nBody.\n');
  await writeFile(join(wsOther, 'INDEX.md'), '<!-- sentinel: hand-maintained index that must survive -->\n');
  // Global long-term with described files — must NEVER get an INDEX.md.
  await writeFile(join(globalLongTerm, 'alpha.md'), '# Alpha\n\nDescription: First description.\n\nAlpha body.\n');
  await writeFile(join(globalLongTerm, 'gamma.md'), '# Gamma\n\nNo description here.\n');
  return {
    scratch,
    home,
    globalLongTerm,
    wsOne,
    wsOther,
    nested,
    emptyProject,
    dispose: () => rm(scratch, { recursive: true, force: true }),
  };
})();
after(() => fx.dispose());

test('regenerates only the current workspace index (cwd climbs to the marker)', async () => {
  const { stdout } = await run(process.execPath, [script, '--home', fx.home], { cwd: fx.nested });
  assert.ok(stdout.includes('DSH home:'), 'the resolved home is reported');
  assert.ok(stdout.includes('current workspace: "ws-one"'), 'the workspace is derived from the cwd');
  assert.ok(stdout.includes('memories/workspace/ws-one: 2 entries -> INDEX.md'));
  const index = await readFile(join(fx.wsOne, 'INDEX.md'), 'utf8');
  assert.ok(index.startsWith('<!-- Generated by scripts/generate-index.mjs'));
  assert.ok(index.includes('- Release process (release.md) — Ship it.'));
  assert.ok(index.endsWith('\n'));
});

test('the global store and every other workspace stay untouched', async () => {
  await assert.rejects(access(join(fx.globalLongTerm, 'INDEX.md')),
    'the global long-term store must never get an INDEX.md');
  const other = await readFile(join(fx.wsOther, 'INDEX.md'), 'utf8');
  assert.ok(other.includes('sentinel: hand-maintained index that must survive'),
    'another workspace store keeps its existing index byte-for-byte');
});

test('ignores files without a Description line', async () => {
  const index = await readFile(join(fx.wsOne, 'INDEX.md'), 'utf8');
  assert.ok(!index.includes('notes') && !index.includes('Notes'));
  assert.ok(
    (await readFile(join(fx.wsOne, 'notes.md'), 'utf8')).includes('No description here.'),
    'the descriptionless file itself is untouched',
  );
});

test('truncates descriptions over 1000 chars with an honest ellipsis, file untouched', async () => {
  const index = await readFile(join(fx.wsOne, 'INDEX.md'), 'utf8');
  const line = index.split(/\r?\n/).find((l) => l.startsWith('- Huge (huge.md) — '));
  assert.ok(line !== undefined, 'huge is listed');
  assert.equal(line, `- Huge (huge.md) — ${'q'.repeat(999)}…`);
  const raw = await readFile(join(fx.wsOne, 'huge.md'), 'utf8');
  assert.ok(raw.includes(`Description: ${'q'.repeat(1500)}`), 'the hand-edited file keeps its 1500-char description');
});

test('on-disk artifact is byte-identical to the plugin read-only synthesis', async () => {
  const onDisk = await readFile(join(fx.wsOne, 'INDEX.md'), 'utf8');
  assert.equal(onDisk, `${await composeIndexDocument(fx.wsOne)}\n`);
});

test('a workspace with no store yet reports honestly and writes nothing', async () => {
  const { stdout } = await run(process.execPath, [script, '--home', fx.home], { cwd: fx.emptyProject });
  assert.ok(stdout.includes('current workspace: "ws-empty"'));
  assert.ok(stdout.includes('no store yet — nothing to do'));
  await assert.rejects(access(join(fx.home, 'memories', 'workspace', 'ws-empty')));
});

test('DSH_HOME env precedence works without --home', async () => {
  await rm(join(fx.wsOne, 'INDEX.md'));
  await run(process.execPath, [script], { cwd: fx.nested, env: { ...process.env, DSH_HOME: fx.home } });
  const index = await readFile(join(fx.wsOne, 'INDEX.md'), 'utf8');
  assert.ok(index.includes('- Release process (release.md) — Ship it.'));
});
